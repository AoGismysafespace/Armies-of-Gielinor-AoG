# ==============================================================================
# restore_milestone.ps1: Automated Milestone Switcher & Rollback Utility
#
# 1. PURPOSE & ARCHITECTURAL CONTEXT:
#    During development of Armies of Gielinor reverse engineering and multiplayer
#    patches, subtle issues (such as desynchronization, packet framing errors, or
#    screen darkening state freezes) can introduce regressions.
#    This script enables guaranteed, deterministic 1-click rollback or switching
#    between verified, functioning milestones without guesswork or manual file handling.
#
# 2. MILESTONE REGISTRY:
#    - v1.0.2: Partially Functional Multiplayer
#              (Lobby joining, Steam P2P socket tunneling, match start, and UI
#               interaction work; combat strike packets are not yet pumped).
#    - v1.0.3: Working Multiplayer Combat
#              (Lobby, match start, and dynamic FIFO battle event pump enabled;
#               movement [kr / 0x00] and combat strike [ag / 0x60, 10 bytes] packets
#               stream to both host and guest in lockstep).
#    - v1.0.4: Fully Functional Multiplayer Combat & Unit Slaying
#              (Lobby, match start, battle event pump, and scoped duplicate death suppression;
#               eliminates redundant Packet 68 'hp' packets that trigger tb.a "Can see death"
#               disconnect veils, allowing combat strikes and unit slayings to resolve cleanly).
#    - v1.0.5: Full Win/Loss Conditions & Authoritative Match Ending
#              (Evaluates active objectives [up.java: Total Portal Loss / Barbarian Denial, mc.java: Total Unit Loss]
#               and game thresholds [Victory Points, turn limits]. Authoritatively marks players eliminated,
#               broadcasts Packet 73 and Packet 69, cleanly triggering the official Victory / Defeat screen).
#    - v1.0.6: Spectator Banner Auto-Dismiss & Real-Time Map Scrolling Sync
#              (Coordinates client turn readiness [Opcode 73] with server turn unpause broadcasts [Packet 76]
#               and 2.5s safety fallback. Resolves spectator banner freezing at tick 50 and unlocks map scrolling).
#    - v1.0.7: Combat Turn Persistence & Timer Pause
#              (Retains turn during combat strikes by pausing turn timer while modal animation plays).
#    - v1.0.8: Post-Combat Turn Retention & Multi-Turn Move Desync Elimination (RECOMMENDED / CURRENT)
#              (Suppresses spurious client-side turn skips generated by multi-turn pathing during combat,
#               ensuring active player retains control until explicitly clicking End Turn or timer expires).
#
# 3. ROSETTA STONE / SYMBOL MAPPINGS:
#    - ArmiesOfGielinor.jar: Patched game JAR containing StandaloneRunner, AoGServer, and AoGBattleBridge.
#    - AoGServer: Multiplayer host server handling TCP lobbies, packets, and turn coordination.
#    - AoGBattleBridge: BattleEngine simulation bridge coordinating serverHa and client packets.
#    - RestoreAndVerify: Integrity audit tool verifying all 719 classes are Java 18 (major <= 62.0).
#    - Target JARs:
#        * extracted/app/ArmiesOfGielinor.jar (Staging source for ZIP builds)
#        * ArmiesOfGielinor/app/ArmiesOfGielinor.jar (Live local playable instance)
#        * %LOCALAPPDATA%/ArmiesOfGielinor_App/app/ArmiesOfGielinor.jar (Installed runtime)
#
# 4. INLINE EXPLANATIONS:
#    Validates milestone existence in backups/, copies target milestone JAR, and invokes
#    RestoreAndVerify to ensure runtime bytecode version compliance before completing.
# ==============================================================================

param (
    [string]$TargetVersion = "v1.0.8"
)

$ErrorActionPreference = "Stop"

if ([string]::IsNullOrEmpty($PSScriptRoot)) {
    $workspace = (Get-Item ".").FullName
} else {
    $workspace = $PSScriptRoot
}
# If invoked from tools/ or subfolder, resolve parent workspace root
if (-not (Test-Path (Join-Path $workspace "extracted"))) {
    if (Test-Path (Join-Path $workspace "..\extracted")) {
        $workspace = (Resolve-Path (Join-Path $workspace "..")).Path
    } elseif (Test-Path (Join-Path $workspace "..\..\extracted")) {
        $workspace = (Resolve-Path (Join-Path $workspace "..\..")).Path
    }
}

$backupDir = Join-Path $workspace "backups"
$extractedJar = Join-Path $workspace "extracted\app\ArmiesOfGielinor.jar"
$liveJar = Join-Path $workspace "ArmiesOfGielinor\app\ArmiesOfGielinor.jar"
$appDataJar = Join-Path $env:LOCALAPPDATA "ArmiesOfGielinor_App\app\ArmiesOfGielinor.jar"

Write-Host "=== Armies of Gielinor Milestone Restoration Utility ==="
Write-Host "Target Milestone: $TargetVersion"

$sourceJar = $null
if ($TargetVersion -eq "v1.0.2" -or $TargetVersion -eq "1.0.2") {
    $sourceJar = Join-Path $backupDir "ArmiesOfGielinor_v1.0.2_milestone.jar"
    if (-not (Test-Path $sourceJar)) {
        $sourceJar = Join-Path $backupDir "ArmiesOfGielinor.jar.backup_pre_combat_fix"
    }
} elseif ($TargetVersion -eq "v1.0.3" -or $TargetVersion -eq "1.0.3") {
    $sourceJar = Join-Path $backupDir "ArmiesOfGielinor_v1.0.3_milestone.jar"
} elseif ($TargetVersion -eq "v1.0.4" -or $TargetVersion -eq "1.0.4") {
    $sourceJar = Join-Path $backupDir "ArmiesOfGielinor_v1.0.4_milestone.jar"
} elseif ($TargetVersion -eq "v1.0.5" -or $TargetVersion -eq "1.0.5") {
    $sourceJar = Join-Path $backupDir "ArmiesOfGielinor_v1.0.5_milestone.jar"
} elseif ($TargetVersion -eq "v1.0.6" -or $TargetVersion -eq "1.0.6") {
    $sourceJar = Join-Path $backupDir "ArmiesOfGielinor_v1.0.6_milestone.jar"
} elseif ($TargetVersion -eq "v1.0.7" -or $TargetVersion -eq "1.0.7") {
    $sourceJar = Join-Path $backupDir "ArmiesOfGielinor_v1.0.7_milestone.jar"
} elseif ($TargetVersion -eq "v1.0.8" -or $TargetVersion -eq "1.0.8") {
    $sourceJar = Join-Path $backupDir "ArmiesOfGielinor_v1.0.8_milestone.jar"
} else {
    Write-Error "Unknown milestone: $TargetVersion. Valid options: 'v1.0.2', 'v1.0.3', 'v1.0.4', 'v1.0.5', 'v1.0.6', 'v1.0.7', 'v1.0.8'."
    exit 1
}

if (-not (Test-Path $sourceJar)) {
    Write-Error "Milestone backup JAR not found at: $sourceJar"
    exit 1
}

Write-Host "Found verified milestone source: $sourceJar"
Write-Host "File size: $((Get-Item $sourceJar).Length) bytes"

# 1. Restore to extracted staging directory
Write-Host "Restoring to extracted staging: $extractedJar..."
Copy-Item $sourceJar $extractedJar -Force

# 2. Restore to live playable folder
if (Test-Path (Join-Path $workspace "ArmiesOfGielinor\app")) {
    Write-Host "Restoring to live playable directory: $liveJar..."
    Copy-Item $sourceJar $liveJar -Force
}

# 3. Restore to AppData local installation
if (Test-Path (Split-Path $appDataJar -Parent)) {
    Write-Host "Restoring to local AppData directory: $appDataJar..."
    Copy-Item $sourceJar $appDataJar -Force
}

# 4. Run bytecode audit
$javaExe = $null
$candidateJavas = @(
    "C:\Program Files\Java\jdk-19\bin\java.exe",
    "C:\Program Files\Eclipse Adoptium\jdk-21.0.4.7-hotspot\bin\java.exe"
)
foreach ($c in $candidateJavas) {
    if (Test-Path $c) { $javaExe = $c; break }
}
if (-not $javaExe) {
    $javaExe = (Get-Command java -ErrorAction SilentlyContinue).Source
}
$restoreClassDir = $null
if (Test-Path (Join-Path $workspace "src\RestoreAndVerify.class")) {
    $restoreClassDir = Join-Path $workspace "src"
} elseif (Test-Path (Join-Path $workspace "RestoreAndVerify.class")) {
    $restoreClassDir = $workspace
} elseif (Test-Path (Join-Path $workspace "tools\RestoreAndVerify.class")) {
    $restoreClassDir = Join-Path $workspace "tools"
}

if ($restoreClassDir) {
    Write-Host "Running bytecode compliance audit..."
    & $javaExe -cp $restoreClassDir RestoreAndVerify $workspace
    if ($LASTEXITCODE -ne 0) {
        Write-Error "Bytecode verification failed after milestone restoration!"
        exit 1
    }
}

Write-Host "=== Successfully restored and verified Milestone $TargetVersion! ==="
